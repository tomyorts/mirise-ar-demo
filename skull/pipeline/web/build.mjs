// Bundles skull/src/main.js into skull/app.js and records file sizes / a version string.
// usage: node build.mjs <site dir>
import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const site = path.resolve(process.argv[2] || '../site');
const sk = path.join(site, 'skull');
const sha = (f) => crypto.createHash('sha256').update(fs.readFileSync(f)).digest('hex');
const size = (f) => fs.statSync(f).size;
const files = { wasm: 'mp/vision_wasm_internal.wasm', model: 'mp/face_landmarker.task', glb: 'anatomy.glb', json: 'anatomy.json' };
const srcDir = path.join(sk, 'src');
const srcs = fs.readdirSync(srcDir).filter((f) => f.endsWith('.js') && !f.endsWith('.gen.js')).sort();
const h = crypto.createHash('sha256');
for (const f of srcs) h.update(fs.readFileSync(path.join(srcDir, f)));
for (const f of Object.values(files)) h.update(sha(path.join(sk, f)));
h.update(fs.readFileSync(path.join(sk, 'app.css')));
h.update(fs.readFileSync(path.join(sk, 'mp/vision_wasm_internal.js')));
h.update(fs.readFileSync(path.join(sk, 'selftest.jpg')));
h.update(fs.readFileSync(fileURLToPath(import.meta.url)));                 // the build itself (it patches the library)
h.update(fs.readFileSync(path.join(here, 'package-lock.json')));          // exact library versions
const version = h.digest('hex').slice(0, 10);          // content hash only: the same inputs always give byte-identical output
const sizes = Object.fromEntries(Object.entries(files).map(([k, f]) => [k, size(path.join(sk, f))]));
fs.writeFileSync(path.join(srcDir, 'build.gen.js'), `// generated by build.mjs\nexport const BUILD = ${JSON.stringify({ version, sizes })};\n`);
// MediaPipe Tasks Vision carries a usage logger: once a minute, and when a task is closed, it posts statistics
// (task type, call counts, timings, platform; no pictures) to a Google server. This page must never contact another
// server, so the logger is switched off in the library code as it is bundled. The page's content security policy
// blocks such a connection as well; this patch makes sure it is not even attempted.
const LIB_PATCHES = [
  ['this.h=setInterval(()=>{this.flush()},6e4)', 'this.error=Error("usage logging is turned off in this build")'],
  ['url:"https://odml.pa.googleapis.com/v1/log"', 'url:"about:blank"'],
];
let libPatched = false;
const noUsageLog = {
  name: 'no-usage-log',
  setup(b) {
    b.onLoad({ filter: /@mediapipe[\\/]tasks-vision[\\/]vision_bundle\.mjs$/ }, async (args) => {
      let code = await fs.promises.readFile(args.path, 'utf8');
      for (const [from, to] of LIB_PATCHES) {
        const n = code.split(from).length - 1;
        if (n !== 1) throw new Error(`expected exactly one "${from}" in ${args.path}, found ${n}: the library has changed, review the usage-logging patch in build.mjs`);
        code = code.replace(from, to);
      }
      libPatched = true;
      return { contents: code, loader: 'js' };
    });
  },
};
const r = await build({
  entryPoints: [path.join(srcDir, 'main.js')], outfile: path.join(sk, 'app.js'), bundle: true, format: 'esm', target: ['es2020', 'safari15'],
  minify: true, legalComments: 'none', nodePaths: [path.join(here, 'node_modules')], logLevel: 'warning', metafile: true, plugins: [noUsageLog],
  banner: { js: `/* MIRAI Skull Mirror（透視ミラー） ${version} — bundles three.js (MIT), MediaPipe Tasks Vision (Apache-2.0; modified: usage logging removed, see skull/pipeline/web/build.mjs) and the meshoptimizer decoder (MIT). Licences: skull/LICENSES.txt. Source: skull/src/ */` },
});
if (!libPatched) throw new Error('the usage-logging patch was not applied: @mediapipe/tasks-vision/vision_bundle.mjs was not bundled');
// audit: the bundle must not name any other server
const ALLOWED_URLS = ['http://www.w3.org/1999/xhtml'];        // an XML namespace name used by three.js, not an address that is contacted
const bundle = fs.readFileSync(path.join(sk, 'app.js'), 'utf8');
const foreign = [...new Set(bundle.match(/(?:https?|wss?):\/\/[^\s"'`)\\]+/g) || [])].filter((u) => !ALLOWED_URLS.includes(u));
if (foreign.length) throw new Error('app.js names other servers: ' + foreign.join(', '));
// stamp the version on the files the page links to, so a new build is never served from an old cache
const htmlPath = path.join(site, 'skull.html');
let html = fs.readFileSync(htmlPath, 'utf8');
html = html.replace(/skull\/app\.css(\?v=[\w.-]+)?/, `skull/app.css?v=${version}`).replace(/skull\/app\.js(\?v=[\w.-]+)?/, `skull/app.js?v=${version}`);
fs.writeFileSync(htmlPath, html);
const inputs = Object.entries(r.metafile.inputs).map(([k, v]) => [k.replace(/.*node_modules\//, ''), v.bytes]).sort((a, b) => b[1] - a[1]).slice(0, 5);
console.log('version', version, 'app.js', size(path.join(sk, 'app.js')), 'bytes; sizes', JSON.stringify(sizes));
