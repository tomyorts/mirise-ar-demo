// Start with the default engine order (GPU, then CPU), then switch engines from the info sheet.
import path from 'node:path';
import { serve, launch, watch, OUT, fakeCameraFile } from './lib.mjs';
const { server, port } = await serve();
const browser = await launch({ fakeCamera: fakeCameraFile() });
const ctx = await browser.newContext({ viewport: { width: 390, height: 780 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true, permissions: ['camera'] });
const page = await ctx.newPage(); const w = watch(page);
await page.goto(`http://127.0.0.1:${port}/skull.html?debug=1`);
await page.waitForTimeout(1500);
const t0 = Date.now();
await page.click('#btnStart');
await page.waitForFunction(() => window.__skull && (window.__skull.S.phase === 'running' || window.__skull.S.phase === 'error'), null, { timeout: 200000 });
console.log('start took', Date.now() - t0, 'ms; phase', await page.evaluate(() => window.__skull.S.phase));
const dbg = () => page.evaluate(() => document.getElementById('debug').textContent.split('\n')[0] + ' | present ' + window.__skull.S.present + ' | q ' + JSON.stringify(window.__skull.S.q));
await page.waitForTimeout(6000); console.log('A', await dbg());
await page.click('#btnInfo'); await page.waitForTimeout(300);
console.log('engine row:', await page.evaluate(() => document.getElementById('engineRow').textContent));
await page.screenshot({ path: path.join(OUT, 'engine_info.png') });
await page.click('#btnEngine'); await page.waitForTimeout(6000);
console.log('toast:', await page.evaluate(() => document.getElementById('toast').textContent), '| row:', await page.evaluate(() => document.getElementById('engineRow').textContent));
await page.click('#btnInfoClose'); await page.waitForTimeout(5000);
console.log('B', await dbg(), '| phase', await page.evaluate(() => window.__skull.S.phase));
await page.click('#btnInfo'); await page.click('#btnEngine'); await page.waitForTimeout(6000);
console.log('toast:', await page.evaluate(() => document.getElementById('toast').textContent), '| row:', await page.evaluate(() => document.getElementById('engineRow').textContent));
await page.click('#btnInfoClose'); await page.waitForTimeout(14000);
console.log('C', await dbg(), '| phase', await page.evaluate(() => window.__skull.S.phase));
await page.screenshot({ path: path.join(OUT, 'engine_run.png') });
console.log('console:', w.console.filter((l) => !/^\[debug\]/.test(l)).slice(0, 30).join('\n   '));
if (w.errors.length) console.log('ERRORS', w.errors.join('\n'));
const ext = [...new Set(w.requests.filter((u) => !u.startsWith(`http://127.0.0.1:${port}/`) && !u.startsWith('blob:') && !u.startsWith('data:')))];
console.log('requests', w.requests.length, 'non-local', JSON.stringify(ext));
await browser.close(); server.close();
